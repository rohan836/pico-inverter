#!/usr/bin/env python3
"""Generate the bitmap digit fonts used by the dashboard.

The panel is 1 bit per pixel, so the only way to get genuinely modern, bold
numerals is to rasterise a real typeface at high resolution and keep a
4-bit-ish coverage byte per pixel.  digits_draw() turns that coverage into
ordered-dither grey on the panel, which gives properly shaped digits with
soft, anti-aliased edges instead of blocky 5x7 upscales.

Output: src/digit_data.c (tables only, no logic).

Run after changing sizes/typeface:
    python tools/gen_digits.py
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "digit_data.c"

TYPE_FACE = r"C:\Windows\Fonts\segoeuib.ttf"
SUPERSAMPLE = 4

# (C symbol, font pixel size, tracking in px)
FONTS = [
    ("digit_font_hero", 34, 2),
    ("digit_font_mid", 26, 1),
    ("digit_font_small", 20, 1),
]


def build_font(size, tracking):
    ss = SUPERSAMPLE
    font = ImageFont.truetype(TYPE_FACE, size * ss)

    inks = []
    for ch in "0123456789":
        box = font.getbbox(ch)
        pad = 8
        w = box[2] - box[0] + 2 * pad
        h = box[3] - box[1] + 2 * pad
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((pad - box[0], pad - box[1]), ch, font=font, fill=255)
        ink = img.getbbox()
        inks.append((img, ink))

    top = min(i[1][1] for i in inks)
    bottom = max(i[1][3] for i in inks)

    glyphs = []
    for img, ink in inks:
        crop = img.crop((ink[0], top, ink[2], bottom))
        w4, h4 = crop.size
        # Box-filter down to the panel resolution.
        small = crop.resize((max(1, w4 // ss), max(1, h4 // ss)), Image.BOX)
        pix = list(small.getdata())
        w, h = small.size
        glyphs.append({"w": w, "h": h, "cov": pix})

    return {"tracking": tracking, "glyphs": glyphs}


def emit(fonts):
    lines = [
        "/* Auto-generated by tools/gen_digits.py -- do not edit by hand. */",
        "#include <stdint.h>",
        "",
        '#include "digits.h"',
        "",
    ]
    for sym, data in fonts.items():
        for idx, g in enumerate(data["glyphs"]):
            name = f"{sym}_g{idx}"
            lines.append(f"static const uint8_t {name}[{g['w'] * g['h']}] = {{")
            row = []
            for i, v in enumerate(g["cov"]):
                row.append(f"{v:3d}")
                if len(row) == 16:
                    lines.append("    " + ",".join(row) + ",")
                    row = []
            if row:
                lines.append("    " + ",".join(row) + ",")
            lines.append("};")
            lines.append("")
        lines.append(f"const digit_glyph_t {sym}_glyphs[10] = {{")
        for idx, g in enumerate(data["glyphs"]):
            lines.append(f"    {{{g['w']}, {g['h']}, {sym}_g{idx}}}, /* {idx} */")
        lines.append("};")
        lines.append("")
        lines.append(
            f"const digit_font_t {sym} = {{ {sym}_glyphs, {data['tracking']} }};"
        )
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")


def main():
    fonts = {sym: build_font(size, tracking) for sym, size, tracking in FONTS}
    emit(fonts)
    for sym, data in fonts.items():
        g = data["glyphs"]
        print(f"{sym}: {g[0]['h']} px cap height, digit widths {[x['w'] for x in g]}")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
